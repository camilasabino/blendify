function plan(
  result: PlanRefinementResponse['result'],
): PlanRefinementResponse {
  return { promptVersion: 'refinement-v1', result };
}

function lessMainstream(): PlanRefinementResponse {
  return plan({
    outcome: 'interpreted',
    patch: {
      ...UNCHANGED_PATCH,
      artists: { add: [], remove: ['Interpol'] },
      popularity: { operation: 'set', value: 'rarities' },
    },
    preservation: {
      ...UNCHANGED_PRESERVATION,
      firstTracks: { operation: 'set', value: 2 },
    },
    unsupportedConstraints: [],
  });
}

function createWorld(
  session: AiSession | null = storedSession(),
  config: Record<string, string> = {},
) {
  const store = new Map<string, AiSession>();
  if (session) {
    store.set(TOKEN, session);
  }
  let lock: string | null = null;
  const sessions = {
    save: jest.fn(),
    find: jest.fn((token: string) => Promise.resolve(store.get(token) ?? null)),
    saveGenerationOutcome: jest.fn(),
    acquireGenerationLock: jest.fn(),
    renewGenerationLock: jest.fn(),
    releaseGenerationLock: jest.fn(),
    hasGenerationLock: jest.fn(),
    savePublishStart: jest.fn(),
    savePublishOutcome: jest.fn(),
    acquireDestinationClaim: jest.fn(),
    renewDestinationClaim: jest.fn(),
    releaseDestinationClaim: jest.fn(),
    hasDestinationClaim: jest.fn(),
    saveIfUnchanged: jest.fn(
      (
        token: string,
        next: AiSession,
        expectedUpdatedAt: string,
        _ttlMs: number,
      ) => {
        if (store.get(token)?.updatedAt !== expectedUpdatedAt) {
          return Promise.resolve(false);
        }
        store.set(token, next);
        return Promise.resolve(true);
      },
    ),
    acquireRefinementLock: jest.fn((_token: string, _ttlMs: number) => {
      if (lock) {
        return Promise.resolve<string | null>(null);
      }
      lock = 'lock-1';
      return Promise.resolve<string | null>(lock);
    }),
    renewRefinementLock: jest.fn(() => Promise.resolve(true)),
    releaseRefinementLock: jest.fn((_token: string, lockId: string) => {
      if (lock === lockId) {
        lock = null;
      }
      return Promise.resolve();
    }),
  } satisfies AiSessionRepositoryPort;
  const planner = {
    planRefinement: jest.fn<
      Promise<PlanRefinementResponse>,
      [PlanRefinementRequest]
    >(() => Promise.resolve(lessMainstream())),
  };
  const catalog = {
    searchArtists: jest.fn((name: string) =>
      Promise.resolve([
        Artist.create({
          id: ArtistId.create(`${name.toLowerCase()}-id`),
          name,
        }),
      ]),
    ),
    searchTracks: jest.fn(() => Promise.resolve([])),
    resolveTrack: jest.fn(() => Promise.resolve(null)),
    getArtistsByIds: jest.fn(() => Promise.resolve([])),
  };
  const catalogs = { forMarket: jest.fn(() => catalog) };
  const discovery = {
    getTopTagsForArtist: jest.fn(() => Promise.resolve([])),
  } as unknown as DiscoveryCatalogPort;
  const generator = {
    execute: jest.fn<Promise<GeneratedPlaylist>, [PlaylistGenerationRequest]>(
      () => Promise.resolve(freshGeneration()),
    ),
  };
  const candidates = new AiRefinementCandidateBuilder(
    new AiIntentResolver(catalogs),
    generator as unknown as GeneratePlaylistUseCase,
    discovery,
  );
  const useCase = new ProposeAiRefinementUseCase(
    sessions,
    planner,
    candidates,
    new ConfigService(config),
  );
  return {
    useCase,
    sessions,
    planner,
    catalogs,
    generator,
    store,
    holdLock: () => {
      lock = 'someone-else';
    },
    takeOverLock: () => {
      lock = 'lock-2';
    },
    dismissPending: () => {
      const current = store.get(TOKEN);
      if (current) {
        store.set(TOKEN, { ...current, pendingRefinement: null });
      }
    },
  };
}

async function errorCode(
  promise: Promise<unknown>,
): Promise<AiSessionErrorCode> {
  const error: unknown = await promise.catch((caught: unknown) => caught);
  expect(error).toBeInstanceOf(AiSessionError);
  return (error as AiSessionError).code;
}

function execute(
  world: ReturnType<typeof createWorld>,
  userId: string | null = null,
) {
  return world.useCase.execute({
    token: TOKEN,
    userId,
    refinement: REFINEMENT,
  });
}

